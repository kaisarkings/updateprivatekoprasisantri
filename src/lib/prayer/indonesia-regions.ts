/**
 * Get distinct list of Indonesian provinces
 */
export function getProvincesList(): string[] {
  const set = new Set<string>();
  ALL_INDONESIA_REGIONS.forEach((r) => set.add(r.provinsi));
  return Array.from(set).sort((a, b) => a.localeCompare('id'));
}

/**
 * Filter Indonesian regions by search keyword and optional province
 */
export function searchIndonesianRegions(
  searchQuery: string,
  provinceFilter?: string
): IndonesianRegion[] {
  const q = (searchQuery || '').trim().toLowerCase();
  const prov = (provinceFilter || '').trim().toLowerCase();

  const filtered = ALL_INDONESIA_REGIONS.filter((r) => {
    if (prov && prov !== 'all' && r.provinsi.toLowerCase() !== prov) {
      return false;
    }
    if (!q) return true;
    return (
      r.kabkota.toLowerCase().includes(q) ||
      r.provinsi.toLowerCase().includes(q) ||
      q.includes(r.kabkota.toLowerCase().replace('kota ', '').replace('kab. ', ''))
    );
  });

  if (!q) return filtered;

  // Rank exact city name matches first
  return filtered.sort((a, b) => {
    const aCity = a.kabkota.toLowerCase();
    const bCity = b.kabkota.toLowerCase();
    const aClean = aCity.replace('kota ', '').replace('kab. ', '');
    const bClean = bCity.replace('kota ', '').replace('kab. ', '');

    const aExact = aClean === q;
    const bExact = bClean === q;
    if (aExact && !bExact) return -1;
    if (!aExact && bExact) return 1;

    const aStarts = aClean.startsWith(q) || aCity.startsWith(q);
    const bStarts = bClean.startsWith(q) || bCity.startsWith(q);
    if (aStarts && !bStarts) return -1;
    if (!aStarts && bStarts) return 1;

    const aContains = aCity.includes(q);
    const bContains = bCity.includes(q);
    if (aContains && !bContains) return -1;
    if (!aContains && bContains) return 1;

    return a.kabkota.localeCompare(b.kabkota);
  });
}

/**
 * Find exact or best matching region by name
 */
export function findRegionByName(cityName: string): IndonesianRegion | undefined {
  if (!cityName) return undefined;
  const clean = cityName.trim().toLowerCase();
  return (
    ALL_INDONESIA_REGIONS.find((r) => r.kabkota.toLowerCase() === clean) ||
    ALL_INDONESIA_REGIONS.find((r) => r.kabkota.toLowerCase().includes(clean)) ||
    ALL_INDONESIA_REGIONS.find((r) => clean.includes(r.kabkota.toLowerCase().replace('kota ', '').replace('kab. ', '')))
  );
}

/**
 * Find nearest region by coordinates (Haversine distance)
 */
export function findNearestRegionFromCoords(lat: number, lon: number): IndonesianRegion {
  let minDistance = Infinity;
  let nearest = ALL_INDONESIA_REGIONS[0];

  for (const r of ALL_INDONESIA_REGIONS) {
    const dLat = (r.lat - lat) * (Math.PI / 180);
    const dLon = (r.lon - lon) * (Math.PI / 180);
    const a =
      Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos(lat * (Math.PI / 180)) *
        Math.cos(r.lat * (Math.PI / 180)) *
        Math.sin(dLon / 2) *
        Math.sin(dLon / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    const dist = 6371 * c;

    if (dist < minDistance) {
      minDistance = dist;
      nearest = r;
    }
  }

  return nearest;
}
